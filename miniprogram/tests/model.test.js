const { test } = require('node:test')
const assert = require('node:assert/strict')
const { quantityInput, weight, scanToken, entryToken, passwordError, requestId, movement } = require('../app/utils/model')

test('weights convert grams to exact thousandths of a jin', () => {
  assert.equal(quantityInput('0.001', 'JIN'), 0.001)
  assert.equal(quantityInput('0.5', 'GRAM'), 0.001)
  assert.equal(quantityInput('1500.5', 'GRAM'), 3.001)
  assert.equal(quantityInput('1.0100', 'JIN'), 1.01)
  assert.equal(weight(3.001, 'GRAM'), '1500.5')
  for (const value of ['0', '-1', '1e2', 'Infinity', '', '0.0001', '0.000000000001', '1.0000000001', '2147483648']) assert.throws(() => quantityInput(value, 'JIN'))
  for (const value of ['0.1', '0.6', '1.25', '0.50000001']) assert.throws(() => quantityInput(value, 'GRAM'), /0.5 克/)
})
test('existing QR labels and encoded mini program entry resolve only a token', () => {
  const token = 'a1234567-1234-4234-8234-123456789abc'
  assert.equal(scanToken(token.toUpperCase()), token)
  assert.equal(scanToken('https://wms.piuiq.com/m/slot/' + token + '?warehouse=2'), token)
  assert.equal(entryToken({ query: { q: encodeURIComponent('https://wms.piuiq.com/m/slot/' + token) } }), token)
  assert.equal(entryToken({ query: { scene: encodeURIComponent(token) } }), token)
  assert.equal(scanToken('pages/operations/index?token=' + token), token)
  assert.equal(entryToken({ query: {} }), '')
  for (const raw of ['https://example.com', token + 'bad', 'wrong-' + token, '%xx']) assert.throws(() => scanToken(raw))
})
test('password byte length, matching and old password constraints', () => {
  assert.equal(passwordError('old', 'new-password-2026', 'new-password-2026'), '')
  assert.match(passwordError('', 'new-password-2026', 'new-password-2026'), /当前密码/)
  assert.match(passwordError('old', 'a'.repeat(73), 'a'.repeat(73)), /72 字节/)
  assert.equal(passwordError('old', '中'.repeat(24), '中'.repeat(24)), '')
  assert.match(passwordError('old', '中'.repeat(25), '中'.repeat(25)), /72 字节/)
  assert.match(passwordError('same-password', 'same-password', 'same-password'), /不能与当前密码相同/)
  assert.match(passwordError('old', 'new-password-2026', 'different-password'), /不一致/)
})
test('request IDs are UUIDs and movement views preserve direction and units', () => {
  assert.match(requestId(), /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/)
  const row = movement({ type: 'OUT', createdAt: 0, quantity: 0.001, beforeQty: 1, afterQty: 0.999, unit: '斤' }, 'GRAM')
  assert.equal(row.amount, '−0.5 克')
  assert.equal(row.balance, '500 → 499.5 克')
  assert.equal(row.label, '出库')
})
